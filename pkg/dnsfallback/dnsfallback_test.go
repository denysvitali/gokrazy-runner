func TestEnsureExistingNameserverPreserved(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "resolv.conf")
	original := "search example.com\nnameserver 192.168.1.1\noptions edns0\n"
	if err := os.WriteFile(path, []byte(original), 0o644); err != nil {
		t.Fatal(err)
	}
	action, err := Ensure(path, DefaultNameservers)
	if err != nil {
		t.Fatalf("Ensure: %v", err)
	}
	if action != ActionUnchanged {
		t.Fatalf("action = %v, want ActionUnchanged", action)
	}
	body, _ := os.ReadFile(path)
	if string(body) != original {
		t.Fatalf("file modified: got %q want %q", body, original)
	}
}

func TestEnsureNameserverWithoutValueNotEnough(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "resolv.conf")
	// A bare "nameserver" with no value should not count as configured.
	if err := os.WriteFile(path, []byte("nameserver\n# foo\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	action, err := Ensure(path, DefaultNameservers)
	if err != nil {
		t.Fatalf("Ensure: %v", err)
	}
	if action != ActionWrote {
		t.Fatalf("action = %v, want ActionWrote", action)
	}
}

func TestEnsureRejectsEmptyArgs(t *testing.T) {
	if _, err := Ensure("", DefaultNameservers); err == nil {
		t.Fatalf("expected error for empty path")
	}
	if _, err := Ensure("/tmp/x", nil); err == nil {
		t.Fatalf("expected error for empty nameservers")
	}
}

func TestEnsurePropagatesReadErrors(t *testing.T) {
	dir := t.TempDir()
	// A directory at the path will cause ReadFile to return EISDIR,
	// which is neither nil nor ErrNotExist — Ensure must surface it.
	path := filepath.Join(dir, "resolv.conf")
	if err := os.MkdirAll(path, 0o755); err != nil {
		t.Fatal(err)
	}
	if _, err := Ensure(path, DefaultNameservers); err == nil {
		t.Fatalf("expected error when path is a directory")
	}
}
