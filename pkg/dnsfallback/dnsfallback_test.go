package dnsfallback

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestEnsureMissingFile(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "resolv.conf")

	action, err := Ensure(path, DefaultNameservers)
	if err != nil {
		t.Fatalf("Ensure: %v", err)
	}
	if action != ActionWrote {
		t.Fatalf("action = %v, want ActionWrote", action)
	}
	body, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	got := string(body)
	if !strings.Contains(got, "nameserver 1.1.1.1") {
		t.Fatalf("missing 1.1.1.1: %s", got)
	}
	if !strings.Contains(got, "nameserver 9.9.9.9") {
		t.Fatalf("missing 9.9.9.9: %s", got)
	}
}

func TestEnsureEmptyFile(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "resolv.conf")
	if err := os.WriteFile(path, []byte(""), 0o644); err != nil {
		t.Fatal(err)
	}
	action, err := Ensure(path, []string{"8.8.8.8"})
	if err != nil {
		t.Fatalf("Ensure: %v", err)
	}
	if action != ActionWrote {
		t.Fatalf("action = %v, want ActionWrote", action)
	}
	body, _ := os.ReadFile(path)
	if !strings.Contains(string(body), "nameserver 8.8.8.8") {
		t.Fatalf("body missing 8.8.8.8: %s", body)
	}
}

